import React from 'react';

/**
 * التأكيدات اتشالت من النظام — بطلب صاحبه.
 *
 * كان كل فعل بيغيّر حاجة بيسأل «متأكد؟» الأول: الحذف، الإقفال، العكس، التعديل على مستند مرحّل.
 * صاحب النظام شاف الرسايل دي وقال يشيلها كلها. القرار قراره: هو اللي بيشغّل الشغل، وهو اللي
 * بيتحمّل نتيجة ضغطة غلط، والسؤال اللي بيتسأل مية مرة في اليوم بيتحوّل لضغطة تانية بتتعمل من
 * غير ما حد يقراها — فبيبقى بيكلّف وقت من غير ما يمنع غلطة.
 *
 * **ده مش بيخلّي الأفعال أخطر مما هي.** كل الحمايات اللي بتقع في السيرفر فاضلة زي ما هي: الحذف
 * لسه بيقفل مش بيمسح، والقيد لسه ما بيتعدلش في مكانه والتصحيح عكس، والفترة المقفولة لسه بترفض.
 * اللي اتشال هو **السؤال** بس، مش الحارس.
 *
 * الشيم ده موجود عشان الشيل يحصل من مكان واحد. لو رجع يوم وقال «رجّعها»، السطر اللي بيرجّعها
 * هنا — مش تلاتين مكان في تلاتين شاشة.
 */
export function Popconfirm({
  children, onConfirm, disabled, ...rest
}: {
  children?: React.ReactNode;
  onConfirm?: (e?: any) => void;
  disabled?: boolean;
  /** باقي خصائص `Popconfirm` بتتقبل وتتجاهل — الاستدعاءات القديمة مااتغيّرتش. */
  [key: string]: any;
}) {
  void rest;
  return (
    <span
      onClick={(e) => {
        if (disabled) return;
        // السطر بيفتح المستند لما يتضغط، وزرار الحذف جوّاه — من غير الوقفة دي، الحذف بيحذف
        // ويفتح الصفحة في نفس الضغطة.
        e.stopPropagation();
        onConfirm?.(e);
      }}
    >
      {children}
    </span>
  );
}

/** بديل `showReversalConfirm` و`showDeactivationConfirm` — بينفّذ من غير ما يسأل. */
export function runWithoutConfirm({ onOk }: { onOk: () => void | Promise<any> }) {
  void onOk();
}

export default Popconfirm;
