// تقسيم ملفات البناء — **المكتبات في ملف لوحدها** (٢٠٢٦-١٠-٠١ — «الريفرش تقيل»).
//
// ملف البداية كان فيه ريأكت وantd وكود البرنامج مع بعض (١٫١ ميجا، ~٤٠٠ك مضغوط). وجوّه
// الكود ده خريطة أسامي ملفات كل الشاشات — فأي تعديل في أي شاشة بيغيّر بصمة الملف كله،
// والمتصفح بيرمي اللي عنده وينزّله من الأول. والنشر بيحصل كذا مرة في اليوم، يعني كل
// يوم كل جهاز بينزّل antd وريأكت تاني وهي ماتغيّرتش.
//
// هنا كل اللي من `node_modules` بيروح `vendor`: بصمته بتتغيّر بس لما مكتبة تتغيّر، فبعد
// النشر العادي المتصفح بينزّل كود البرنامج بس (~٧٠ك مضغوط) وياخد الباقي من الكاش
// (الأصول عليها `immutable` سنة في nginx). الـCSS بيفضل في مكانه.
export function manualChunks(id: string): string | undefined {
  if (id.includes('node_modules') && !id.endsWith('.css')) return 'vendor';
  return undefined;
}
