/// محرك الخصم — **المكان الوحيد اللي بيحسب فيه خصم في التطبيق**.
///
/// سطر الفاتورة، شاشة البيع، ورقة الطباعة — كلهم بينادوا من هنا. مافيش
/// `* (1 - pct / 100)` مكتوبة في شاشة.
///
/// ---------------------------------------------------------------------------
/// **الخصمين بيتطبقوا ورا بعض، مش بيتجمعوا.**
///
///     ١٠٪ وبعدها ٥٪  =  ١٤٫٥٪   مش ١٥٪
///
/// التانية بتتحسب على اللي فضل بعد الأولى. ده مش اختيار جمالي — ده اللي a5 بيعمله،
/// واتقاس على سطوره:
///
///     ٨ × ١٦٦٫٢٥ بخصم ١٠٪ ثم ٥٪  →  ١٬١٣٧٫١٥   ← الرقم اللي على فاتورتهم
///     نفس السطر بالجمع (١٥٪)      →  ١٬١٣٠٫٥٠   ← فرق ٦٫٦٥ على سطر واحد
///
/// **والناتج نسبة واحدة** لأن سطر الفاتورة عنده خانة خصم واحدة — بس محسوبة بالتركيب،
/// وهي اللي بتروح للسيرفر.
///
/// **السقف ٩٩٫٩٩٪.** خصم ١٠٠٪ معناه سطر بصفر، ودي حاجة تتعمل بمسح السطر مش بخصم.
/// الاستثناء الوحيد **فاتورة البونص** (بضاعة هدية): سطرها صفر فعلاً، وده متقال في
/// `SaleDraftLine.discountPct` مش هنا — المحرك نفسه بيفضل زي التانيين بالحرف.
///
/// ⚠️ **والقاعدة دي مكتوبة تلات مرات، مرة لكل لغة** — مافيش طريقة تشارك كود بين Dart
/// وPython وTypeScript. التانيتين:
///
///     backend/src/lib/discounts.py
///     frontend/src/utils/discount.ts
///
/// أي تعديل هنا لازم يتعمل في التلاتة، والمثال اللي فوق (١٬١٣٧٫١٥) مكتوب في التلاتة
/// عشان أي واحدة تفرق تبان في أول قياس.
library;

/// أعلى خصم مسموح. شوف الشرح فوق.
const double kMaxDiscountPct = 99.99;

double _pct(double? v) {
  final n = v ?? 0;
  if (!n.isFinite || n <= 0) return 0;
  return n > 100 ? 100 : n;
}

/// تقريب على منزلتين — `discount_pct` في القاعدة `Numeric(5,2)`.
double _round2(double n) => (n * 100).roundToDouble() / 100;

/// خصمين (أو أكتر) ورا بعض ← نسبة واحدة مكافئة.
///
///     combineDiscounts([10, 5])   → 14.5
///     combineDiscounts([25, 10])  → 32.5
///     combineDiscounts([10])      → 10
///     combineDiscounts([])        → 0
double combineDiscounts(List<double?> percentages) {
  var remaining = 1.0;
  for (final p in percentages) {
    remaining *= (1 - _pct(p) / 100);
  }
  final pct = _round2(100 * (1 - remaining));
  return pct > kMaxDiscountPct ? kMaxDiscountPct : pct;
}

/// المبلغ بعد الخصمين — بيستعمل [combineDiscounts] عشان الرقم يطابق المخزّن.
///
///     applyDiscounts(1330, [10, 5])  → 1137.15
double applyDiscounts(double amount, List<double?> percentages) =>
    amount * (1 - combineDiscounts(percentages) / 100);

/// المبلغ بعد نسبة خصم **واحدة جاهزة** — للسطر اللي خصمه مركّب خلاص.
///
/// نفس حساب [applyDiscounts] بنسبة واحدة، والاسم بيفرّق عشان اللي بيقرا الكود يعرف
/// هو بيركّب نِسب ولا بيطبّق نسبة اتحسبت قبل كده.
double netOf(double amount, double? percentage) =>
    amount * (1 - _pct(percentage) / 100);
