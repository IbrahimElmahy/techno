/// ترتيب أبجدي عربي — **المكان الوحيد اللي بيتقرر فيه ترتيب الأسماء في التطبيق**.
///
/// الترتيب الافتراضي بيرتّب بنقطة الكود، والعربي في يونيكود مش مرتّب أبجدياً بالشكل اللي
/// الناس بتقراه: «أحمد» و«احمد» و«إحسان» بيتفرّقوا في تلات أماكن بعيدة لأن الهمزات حروف
/// مستقلة، و«ة» بتيجي بعد «ي» كلها، و«ى» غير «ي». فالقايمة بتطلع مبعزقة، والمندوب واقف
/// قدام العميل بيدوّر على صنف في قايمة طويلة ومش لاقيه.
///
///     أ إ آ ٱ  →  ا        الهمزة شكل كتابة مش حرف تاني في الترتيب
///     ى        →  ي
///     ة        →  ه
///     ؤ ئ      →  و ي
///     التشكيل والتطويل بيتشالوا — «كوع» و«كـوع» اسم واحد
///
/// الاسم المعروض بيفضل زي ما هو بالحرف: التوحيد ده **للمقارنة بس**.
///
/// ⚠️ **والقاعدة دي مكتوبة تلات مرات، مرة لكل لغة.** التانيتين:
///
///     backend/src/lib/arabic.py
///     frontend/src/utils/arabicSort.ts
///
/// أي تعديل هنا لازم يتعمل في التلاتة، وإلا القايمة اللي السيرفر رتّبها بتتعاد على
/// الجهاز بقاعدة تانية والشاشتين بيقولوا ترتيبين.
library;

const _from = 'أإآٱؤئىة';
const _to = 'ااااوييه';

/// التشكيل والتطويل — بيتشالوا خالص.
final _strip = RegExp('[ـً-ْٰ]');

/// الاسم موحَّد للمقارنة. مش للعرض.
String bare(String? text) {
  final s = (text ?? '').trim().toLowerCase().replaceAll(_strip, '');
  final b = StringBuffer();
  for (final ch in s.split('')) {
    final i = _from.indexOf(ch);
    b.write(i >= 0 ? _to[i] : ch);
  }
  return b.toString();
}

/// مقارنة اسمين أبجدياً — للاستعمال المباشر في `sort`:
///
///     items.sort((a, b) => compareArabic(a.name, b.name));
int compareArabic(String? a, String? b) => bare(a).compareTo(bare(b));

/// بترتّب القايمة في مكانها أبجدياً بالاسم.
void sortByName<T>(List<T> rows, String? Function(T) name) {
  rows.sort((x, y) => compareArabic(name(x), name(y)));
}
