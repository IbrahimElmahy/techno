"""أرقام التليفونات — **المكان الوحيد اللي بيتقرر فيه شكل الرقم الصح**.

الأرقام اتنقلت من إكسل، والإكسل بيتعامل مع خانة فيها أرقام بس كأنها عدد. النتيجة
تلات أشكال من التلف، كلها موجودة في الداتا دلوقتي:

* **الصفر الأول بيتشال.** `01008796013` بيتخزّن `1008796013` — عشان العدد ١٠٠٨٧٩٦٠١٣
  مالوش صفر على شماله. ده أكتر التلف انتشاراً: ١٬٣٠٤ سباك من ١٬٦٨٦ رقمهم كده،
  ومحدش يقدر يرنّ منهم على واحد.
* **قيم نائبة اتنقلت كأنها أرقام.** `1` و`0` و`0000000` — مش أرقام ناقصة، دي خانة
  مالهاش أصل. وخزنها كأنها رقم أسوأ من الفاضي: الشاشة بتوريه، وخدمة العملاء بتحاول
  ترنّ عليه، والكشف بيقول «عنده رقم».
* **أكتر من رقم في خانة واحدة** — مفصولين بشرطة أو فاصلة أو مسافة.

القاعدة هنا بترجّع الشكل اللي بيترنّ: موبايل مصري ١١ رقم يبدأ بـ`01`، أو أرضي يبدأ
بـ`0`. واللي مايوصلش للشكل ده بيرجع `None` — **مش بيتخمّن**. رقم متخمّن بيرنّ على حد
تاني، وده أسوأ من إن الخانة تفضل فاضية وحد يسأل عنها.

بتشتغل على الأرقام العربية والإنجليزية: `٠١٠٠٨٧٩٦٠١٣` و`01008796013` نفس الرقم.
"""
from __future__ import annotations

import re

# أرقام عربية ← إنجليزية. الرقم بيتخزّن بالإنجليزي عشان المقارنة والاتصال.
_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")

# الفواصل اللي بتيجي بين رقمين في نفس الخانة.
_SPLIT = re.compile(r"[،,;/\\\|\n\r\t]+|\s{2,}|\s+-\s+")

# قيم نائبة اتنقلت كأنها أرقام. مش أرقام ناقصة — دي خانات مالهاش أصل.
_PLACEHOLDERS = {"", "0", "1", "00", "000", "0000000", "00000000", "-", ".", "لا يوجد", "لايوجد"}

# بادئات الموبايل المصري بعد الصفر: فودافون/اتصالات/أورنج/وي.
_MOBILE_PREFIX = ("10", "11", "12", "15")


def _bare(value) -> str:
    """الرقم بأرقام إنجليزية وبدون أي حاجة غير الأرقام."""
    text = str(value if value is not None else "").translate(_DIGITS)
    return re.sub(r"\D", "", text)


def normalize(value) -> str | None:
    """رقم واحد بالشكل اللي بيترنّ، أو `None` لو مش رقم.

    * `1008796013`   → `01008796013`   (الصفر اللي الإكسل شاله)
    * `201008796013` → `01008796013`   (كود مصر بدل الصفر)
    * `+20 100 879 6013` → `01008796013`
    * `1` / `0000000` / `` → `None`    (قيمة نائبة، مش رقم ناقص)
    * `12345`        → `None`          (أقصر من أي رقم حقيقي)
    """
    raw = str(value if value is not None else "").strip()
    if raw.casefold() in _PLACEHOLDERS:
        return None
    digits = _bare(raw)
    if not digits or set(digits) == {"0"}:
        return None

    # كود مصر، بـ+ أو من غيره: 20 قبل موبايل بيبدأ بـ1.
    if digits.startswith("0020"):
        digits = digits[4:]
    if len(digits) == 12 and digits.startswith("20") and digits[2] == "1":
        digits = digits[2:]

    # **الصفر اللي الإكسل شاله.** ١٠ خانات بتبدأ ببادئة موبايل ⇒ ناقصها صفر.
    if len(digits) == 10 and digits[:2] in _MOBILE_PREFIX:
        digits = "0" + digits

    if len(digits) == 11 and digits.startswith("0") and digits[1:3] in _MOBILE_PREFIX:
        return digits
    # أرضي: بيبدأ بصفر وطوله من ٧ لـ١٠. والأقصر من كده مش رقم.
    if digits.startswith("0") and 7 <= len(digits) <= 10:
        return digits
    # أرضي من غير كود المحافظة — بيتساب زي ما هو لو طوله معقول، عشان اللي كاتبه
    # يعرف يكمّله. أقل من ٦ خانات مش رقم أصلاً.
    if 6 <= len(digits) <= 10:
        return digits
    return None


def split_numbers(value) -> list[str]:
    """خانة فيها رقم أو أكتر ⇒ قايمة أرقام سليمة، بترتيبها وبدون تكرار.

    «01008796013 - 0453212345» خانة واحدة فيها رقمين، والفصل بينهم هو الفرق بين
    رقمين بيترنّوا ورقم واحد طويل مابيترنّش.
    """
    raw = str(value if value is not None else "").strip()
    if not raw:
        return []
    parts = [p for p in _SPLIT.split(raw) if p.strip()]
    if len(parts) == 1:
        # شرطة واحدة جوّه رقم ممكن تكون فاصل («011-2345678») وممكن تكون بين رقمين.
        # الفصل بيتعمل بس لو الجزئين الاتنين بيطلعوا أرقام لوحدهم.
        dash = re.split(r"\s*-\s*", raw)
        if len(dash) == 2 and all(normalize(d) for d in dash):
            parts = dash
    out: list[str] = []
    for part in parts:
        num = normalize(part)
        if num and num not in out:
            out.append(num)
    return out


def is_placeholder(value) -> bool:
    """القيمة دي خانة مالهاش أصل (`1` / `0` / `0000000`) مش رقم ناقص؟"""
    return normalize(value) is None and str(value or "").strip() != ""


def display(value) -> str:
    """الرقم زي ما بيتعرض — الشكل الصح لو ينفع، وإلا فاضي بدل قيمة نائبة."""
    return normalize(value) or ""
