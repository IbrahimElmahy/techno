"""ترتيب أبجدي عربي — **المكان الوحيد اللي بيتقرر فيه ترتيب الأسماء**.

الترتيب الافتراضي للقاعدة بيرتّب بنقطة الكود (code point)، والعربي في يونيكود مش مرتّب
أبجدياً بالشكل اللي الناس بتقراه: «أحمد» و«احمد» و«إحسان» بيتفرّقوا في تلات أماكن بعيدة
عن بعض لأن الهمزات حروف مستقلة، و«ة» بتيجي بعد «ي» كلها، و«ى» غير «ي».

فالقايمة بتطلع مبعزقة: الصنف اللي بيبدأ بـ«أ» مش جنب اللي بيبدأ بـ«ا»، واللي بيدوّر
بعينه على اسم في كشف طويل بيعدّي عليه ومايشوفوش.

---------------------------------------------------------------------------
**التوحيد قبل المقارنة، والأصل مابيتغيّرش.**

    أ إ آ ٱ  →  ا        الهمزة شكل كتابة مش حرف تاني في الترتيب
    ى        →  ي        الألف المقصورة بتتكتب بالشكلين لنفس الاسم
    ة        →  ه        وكذلك التاء المربوطة
    ؤ ئ      →  و ي
    التشكيل والتطويل     بيتشال — «كوع مفتوح» و«كـوع مفتوح» اسم واحد

الاسم المعروض بيفضل زي ما هو بالحرف: التوحيد ده **للمقارنة بس**.

**ومحسوب في SQL مش في بايثون** (`sort_key`) عشان التقطيع (`limit`/`offset`) يفضل صح:
ترتيب في الذاكرة بعد ما الصفحة اتجابت بيرتّب الصفحة جوّه نفسها والكشف كله يفضل مبعزق.
و`bare` هي نفس القاعدة لبايثون، للقوايم اللي اتجمّعت خلاص في الذاكرة.

⚠️ **والقاعدة دي مكتوبة تلات مرات، مرة لكل لغة** — زي محرك الخصم بالظبط. التانيتين:

    frontend/src/utils/arabicSort.ts
    mobile/lib/models/arabic_sort.dart
"""
from __future__ import annotations

from sqlalchemy import func

# حرف → اللي بيتقارن بيه. الترتيب هنا مالوش معنى، ده استبدال حرف بحرف.
_FROM = "أإآٱؤئىة"
_TO___ = "ااااوييه"

# بيتشال خالص: التشكيل والتطويل. الحرف الفاضي في `translate` معناه «احذف».
_STRIP = "ـًٌٍَُِّْٰ"

# ---------------------------------------------------------------- الأرقام
#
# **الأرقام بتتعرض عربية، وبتتخزّن وبتتقارن إنجليزية.**
#
# اسم الصنف جاي من النقل بأرقام إنجليزية («بلاعة 2 ×1.5 تكنوو 7 سم») وسط كلام عربي،
# والفلوس والكميات على نفس الشاشة بتتعرض بأرقام عربية (`toLocaleString('ar-EG')`).
# فالسطر الواحد فيه الشكلين، والعين بتتلخبط.
#
# والتخزين بيفضل إنجليزي: الاسم المخزّن هو اللي بيتقارن بـa5، وأي سكربت بيطابق
# بالاسم كان هيقع لو الحروف اتغيّرت تحته. فالتحويل عند القراءة بس.
_EASTERN = "٠١٢٣٤٥٦٧٨٩"
_WESTERN = "0123456789"
# الأرقام الفارسية بتيجي من نسخ ولصق — بتتحسب نفس العربية.
_PERSIAN = "۰۱۲۳۴۵۶۷۸۹"

_TO_EASTERN = str.maketrans(_WESTERN, _EASTERN)
_TO_WESTERN = str.maketrans(_EASTERN + _PERSIAN, _WESTERN + _WESTERN)


def eastern_digits(text: str | None) -> str | None:
    """الأرقام الإنجليزية في النص تبقى عربية — **للعرض بس**.

        «بلاعة 2 ×1.5 تكنوو 7 سم»  →  «بلاعة ٢ ×١.٥ تكنوو ٧ سم»

    الحروف والرموز مابتتلمسش، والعلامة العشرية بتفضل نقطة زي ما هي.
    """
    if text is None:
        return None
    return text.translate(_TO_EASTERN)


def western_digits(text: str | None) -> str | None:
    """العكس — بيتعمل على اللي بيتكتب في خانة بحث قبل ما يتقارن بالمخزّن.

    من غيره اللي بيكتب «٢» بلوحة عربية مابيلاقيش «2» المخزّنة.
    """
    if text is None:
        return None
    return text.translate(_TO_WESTERN)


def sort_key(column):
    """تعبير SQL بيرجّع الاسم موحَّد — للاستعمال في `order_by`.

        stmt.order_by(arabic.sort_key(Item.name), Item.name)

    الاسم الأصلي بيتحط بعده كفاصل تعادل، عشان صنفين اختلافهم في الهمزة بس يفضلوا
    بترتيب ثابت بدل ما يتبادلوا مع كل استعلام.
    """
    return func.translate(
        func.translate(
            func.translate(func.lower(column), _EASTERN + _PERSIAN, _WESTERN + _WESTERN),
            _STRIP, ""),
        _FROM, _TO___)


def match_order(needle: str | None, *columns):
    """تعبير SQL بيرتّب نتايج البحث بالقُرب — **اللي بيبدأ بالحروف الأول**.

        stmt.order_by(*arabic.match_order(q, Item.name, Item.code),
                      arabic.sort_key(Item.name), Item.name)

    **المشكلة:** البحث بيلاقي الحروف في أي مكان في الاسم (`%كذا%`)، والترتيب بعد كده
    أبجدي على طول. يعني صنف الحروف فيه في **آخر كلمة** بيطلع فوق صنف **بيبدأ** بيها،
    لأن الأبجدي مابيعرفش إن ده بحث أصلاً. اللي بيكتب «كوع» عايز «كوع ٢ باب» مش
    «جلبة وصل كوع».

    والمراتب تلاتة:

        ٠  الاسم كله بيبدأ بالحروف        «كوع» ← «كوع ٢ باب سوبر»
        ١  كلمة جوّه الاسم بتبدأ بيها      «كوع» ← «جلبة كوع ٤"»
        ٢  موجودة جوّه كلمة                «كوع» ← «مكوعة»

    وبيرجّع **تُبل** عشان يتفرد بـ`*`: من غير بحث بيرجع فاضي فمافيش معيار يتضاف.

    وجوّه المرتبة الواحدة الترتيب أبجدي زي ما هو، فالكشف يفضل مقروء.

    **والمقارنة على الاسم الموحَّد** (`sort_key`): من غير كده اللي بيكتب «احمد»
    مابيلاقيش «أحمد»، واللي بيكتب «جلبه» مابيلاقيش «جلبة» — وده كان بيحصل فعلاً،
    لأن الترتيب كان بيوحّد والبحث لأ.
    """
    from sqlalchemy import case

    n = bare(needle) if needle else ""
    if not n:
        # **تُبل فاضي، مش صفر.** رجّعنا `literal(0)` مرة، وPostgres قرا
        # `ORDER BY 0` على إنه رقم عمود في الـSELECT ورمى
        # «ORDER BY position 0 is not in select list» — كل كشف أصناف من غير بحث وقع.
        # الشكل ده بيمنع الغلط ده أصلاً: مافيش بحث ⇒ مافيش معيار يتضاف.
        return ()
    whens = []
    for col in columns:
        k = sort_key(col)
        whens.append((k.like(f"{n}%"), 0))
    for col in columns:
        k = sort_key(col)
        # كلمة جوّه الاسم بتبدأ بالحروف: مسبوقة بمسافة أو بفاصل.
        whens.append((k.like(f"% {n}%"), 1))
    return (case(*whens, else_=2),)


def bare(text: str | None) -> str:
    """نفس التوحيد لبايثون — للقوايم اللي في الذاكرة.

        rows.sort(key=lambda r: arabic.bare(r.name))
    """
    s = (text or "").strip().lower().translate(_TO_WESTERN)
    for ch in _STRIP:
        s = s.replace(ch, "")
    return s.translate(str.maketrans(_FROM, _TO___))
