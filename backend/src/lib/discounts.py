"""الخصم بعد الخصم — القاعدة الواحدة اللي كل حسبة خصم في النظام بتعدّي منها.

النظام كان بيجمع النِسَب على بعضها: صنف خصمه ١٠٪ وعليه خصم متغيّر ٥٪ كان بيطلع
١٥٪. وده **مش** اللي بيحصل في السوق ولا في النظام القديم — الخصم التاني بيتحسب على
**الباقي** بعد الأول، مش على السعر الأصلي:

    ١٠٠ × (١ − ٠٫١٠) = ٩٠      ← بعد خصم الصنف
     ٩٠ × (١ − ٠٫٠٥) = ٨٥٫٥٠   ← الخصم المتغيّر على الباقي

يعني النسبة الفعلية ١٤٫٥٪ مش ١٥٪. الفرق بيبان صغير على مية جنيه، وبيبقى فلوس
حقيقية على فاتورة بمية ألف — وبيكبر كل ما الخصمين يكبروا (٥٠٪ + ٥٠٪ بالجمع
بيوصلوا صفر، وبالصح بيوصلوا ٢٥٪ من السعر).

**النسبة المجمّعة مشتقّة، مش مخزّنة كقاعدة.** المستند بيحتفظ بالخصمين الأصليين
(`fixed_discount_pct` و`variable_discount_pct`) و`combined_pct` هي الحصيلة —
بتتكتب عشان اللي بيقرا الفاتورة يشوف نسبة واحدة، مش عشان يتحسب منها المبلغ.
المبلغ بيتحسب من `apply` مباشرةً بالنِسَب الأصلية، فمافيش تقريب في النص.

الترتيب مالوش لازمة حسابياً — الضرب تبديلي — فـ«الثابت الأول» مش قاعدة، هو بس
اللي بيتكتب على الورقة كده.
"""
from __future__ import annotations

from decimal import Decimal

from src.core.money import to_money

HUNDRED = Decimal("100")
ONE = Decimal("1")


def _factor(pct: Decimal | float | str | None) -> Decimal:
    """الباقي بعد نسبة واحدة — ٢٠٪ بترجع ٠٫٨٠."""
    return ONE - (Decimal(str(pct or 0)) / HUNDRED)


def remaining(*pcts: Decimal | float | str | None) -> Decimal:
    """الباقي بعد كل النِسَب ورا بعض — بدقّة كاملة من غير تقريب."""
    out = ONE
    for p in pcts:
        out *= _factor(p)
    return out


def combine(*pcts: Decimal | float | str | None) -> Decimal:
    """النسبة الفعلية للخصمين مع بعض — ١٠٪ ثم ٥٪ = ١٤٫٥٠٪.

    بتترجع بمنزلتين عشان العمود `PCT` بياخد منزلتين. القيمة دي **للعرض**؛ المبلغ
    بيتحسب من `apply` بالنِسَب الأصلية عشان التقريب ده مايدخلش في الفلوس.
    """
    return (HUNDRED * (ONE - remaining(*pcts))).quantize(Decimal("0.01"))


def apply(amount: Decimal | float | str, *pcts: Decimal | float | str | None) -> Decimal:
    """المبلغ بعد الخصومات ورا بعض، مقرّب للقرش مرة واحدة في الآخر."""
    return to_money(Decimal(str(amount)) * remaining(*pcts))
