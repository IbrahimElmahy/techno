"""محرك الخصم — **المكان الوحيد اللي بيحسب فيه خصم في البايثون**.

كل حاجة بتخصم بتنده من هنا: البيع، الشرا، المرتجعات، شاشة معلومات المنتج، سكربتات
النقل. مافيش `× (1 - pct/100)` مكتوبة في مكان تاني.

---------------------------------------------------------------------------
**الخصمين بيتطبقوا ورا بعض، مش بيتجمعوا.**

    ١٠٪ وبعدها ٥٪  =  ١٤٫٥٪   مش ١٥٪

التانية بتتحسب على اللي فضل بعد الأولى. ده مش اختيار جمالي — ده اللي a5 بيعمله،
واتقاس على سطوره:

    ٨ × ١٦٦٫٢٥ بخصم ١٠٪ ثم ٥٪  →  ١٬١٣٧٫١٥   ← الرقم اللي على فاتورتهم
    نفس السطر بالجمع (١٥٪)      →  ١٬١٣٠٫٥٠   ← فرق ٦٫٦٥ على سطر واحد

الجمع كان بيخلّي كل فاتورة فيها خصمين تفرق عن نظامهم، والفرق بيكبر مع الكمية.

**والناتج نسبة واحدة** لأن سطر الفاتورة عنده خانة خصم واحدة (`discount_pct`) — بس
محسوبة بالتركيب. يعني المخزّن في القاعدة هو ١٤٫٥ مش ١٠ و٥.

**السقف ٩٩٫٩٩٪.** خصم ١٠٠٪ معناه سطر بصفر، ودي حاجة تتعمل بمسح السطر مش بخصم —
والسطر بصفر بيكسر حساب التكلفة والنقاط ورا.

⚠️ **والقاعدة دي مكتوبة تلات مرات، مرة لكل لغة** — مافيش طريقة تشارك كود بين بايثون
وTypeScript وDart. التانيتين:

    frontend/src/utils/discount.ts
    mobile/lib/models/discount.dart

أي تعديل هنا لازم يتعمل في التلاتة، والمثال اللي فوق (١٬١٣٧٫١٥) مكتوب في التلاتة
عشان أي واحدة تفرق تبان في أول قياس.
"""
from __future__ import annotations

from decimal import Decimal

from src.core.money import to_money

ZERO = Decimal("0")
HUNDRED = Decimal("100")
# أعلى خصم مسموح. شوف الشرح فوق.
MAX_PCT = Decimal("99.99")


def _pct(value) -> Decimal:
    """أي رقم داخل → نسبة مضمونة بين صفر ومية."""
    if value is None:
        return ZERO
    d = Decimal(str(value))
    if d < ZERO:
        return ZERO
    return d if d <= HUNDRED else HUNDRED


def combine(*percentages) -> Decimal:
    """خصمين (أو أكتر) ورا بعض → نسبة واحدة مكافئة، مقرّبة على منزلتين.

        combine(10, 5)      → Decimal('14.50')
        combine(25, 10)     → Decimal('32.50')
        combine(10)         → Decimal('10.00')
        combine()           → Decimal('0.00')

    التقريب على منزلتين لأن `discount_pct` في القاعدة `Numeric(5,2)` — والرقم اللي
    بيترجع هو اللي هيتخزّن، فالتقريب بيحصل هنا مرة مش عند كل واحد بيخزّن.
    """
    remaining = Decimal("1")
    for p in percentages:
        remaining *= (Decimal("1") - _pct(p) / HUNDRED)
    pct = to_money(HUNDRED * (Decimal("1") - remaining))
    return pct if pct <= MAX_PCT else MAX_PCT


def apply(amount, *percentages) -> Decimal:
    """المبلغ بعد الخصمين — بيستعمل [combine] عشان الرقم يطابق المخزّن بالظبط.

        apply(Decimal("1330"), 10, 5)  → Decimal('1137.15')

    **بيخصم بالنسبة المقرّبة مش بالكسر الكامل** عن قصد: السطر المخزّن بيقول ١٤٫٥٪،
    واللي بيراجع الورقة بيضرب ١٤٫٥٪ ويطلع نفس الرقم. لو خصمنا بالكسر الكامل هنا،
    الإجمالي مايضربش مع النسبة المكتوبة جنبه وحد هيسأل.
    """
    base = Decimal(str(amount or 0))
    return to_money(base * (Decimal("1") - combine(*percentages) / HUNDRED))


def net_of(amount, pct) -> Decimal:
    """المبلغ بعد نسبة خصم **واحدة جاهزة** — للسطر اللي خصمه متخزّن مركّب خلاص.

    مش نفس `apply(amount, pct)` في المعنى وإن كان نفس الحساب: دي بتقول «النسبة دي
    محسوبة خلاص، طبّقها»، والتانية بتقول «ركّب النِسب دي وطبّقها». الاسم بيفرّق
    عشان اللي بيقرا الكود يعرف هو في أنهي حالة.
    """
    return to_money(Decimal(str(amount or 0)) * (Decimal("1") - _pct(pct) / HUNDRED))


def implied_pct(before, after) -> Decimal:
    """الخصم المستنتج من مبلغين — «كان كذا وبقى كذا، يبقى الخصم كام؟».

        implied_pct(5200, 4160)  → Decimal('20.00')
        implied_pct(1330, 1137.15) → Decimal('14.50')

    **بيتستعمل في النقل من a5.** سطر الفاتورة عندهم بيشيل سعر الوحدة الخام وإجمالي
    السطر بعد الخصم، والنسبة اللي بينهم مش متخزّنة في العمود اللي بنقراه — فبتتحسب.
    مافيش تخمين هنا: الرقمين الاتنين حقيقيين والنسبة نتيجتهم.

    الصفر بيرجع لما المبلغ الأساسي صفر أو الإجمالي أكبر منه (زيادة مش خصم) — ومابنكتبش
    رقم سالب في خانة اسمها «خصم».
    """
    base = Decimal(str(before or 0))
    net = Decimal(str(after or 0))
    if base <= ZERO or net >= base:
        return ZERO
    pct = to_money(HUNDRED * (base - net) / base)
    return pct if pct <= MAX_PCT else MAX_PCT
