"""اسم بيتخزّن بأرقام إنجليزية وبيترجع بأرقام عربية — **نوع عمود، مش سطر عرض**.

## المشكلة

أسماء الأصناف اتنقلت من a5 بأرقام إنجليزية وسط كلام عربي: «بلاعة 2 ×1.5 تكنوو 7 سم».
وكل رقم تاني على نفس الشاشة — الكمية والسعر والإجمالي — بيتعرض بأرقام عربية، لأن
الواجهة بتعدّيه على `toLocaleString('ar-EG')`. فالسطر الواحد فيه الشكلين مع بعض.

## ليه نوع عمود مش تحويل عند العرض

الاسم بيتقرا من **٥٥ موضع في ١٨ ملف** — الكتالوج، الفواتير، المرتجعات، أذون الصرف،
الجرد، الحجوزات، كارت الصنف، التقارير، ملف العميل، ملف المورّد، فحص النظام. تحويل
عند كل موضع معناه إن أول شاشة أو تقرير جديد هيتكتب من غير التحويل، والفرق هيرجع تاني
من حتة مش متوقّعة.

النوع بيشتغل عند **قراءة العمود نفسه**، فأي استعلام بيسحب الاسم — بالكيان أو بعمود
لوحده (`select(Item.name)`) — بياخد الشكل المعروض من غير ما يعرف حاجة عن الموضوع.
والتطبيق والطباعة والتصدير بياخدوه معاه، لأنهم كلهم بيقروا من نفس المصدر.

## والمخزّن بيفضل إنجليزي

الكتابة مابتتغيّرش: اللي بيتحفظ في القاعدة هو اللي اتكتب. تلات أسباب:

* **المطابقة مع a5.** الاسم المخزّن هو اللي بيتقارن بالنظام القديم، وأي سكربت بيطابق
  بالاسم كان هيقع لو الحروف اتغيّرت تحته.
* **البحث.** `LIKE` بيتعمل على المخزّن، واللي بيكتب «2» بلوحة إنجليزية لازم يلاقيها.
  واللي بيكتب «٢» بيتحوّل بـ`arabic.western_digits` قبل المقارنة.
* **الرجوع.** تغيير في العرض بيترجع بسطر؛ تغيير في ٢٬٦٣٠ صف بيحتاج سكربت تاني.

⚠️ التحويل **للعرض بس**: النص اللي راجع مايتحطّش في `WHERE` ولا يتبعت للسيرفر تاني
كمفتاح — استعمل القيمة اللي في القاعدة لده.
"""
from __future__ import annotations

from sqlalchemy import String, TypeDecorator

from src.lib import arabic


class DisplayName(TypeDecorator):
    """`String` عادي، بس بيرجّع أرقامه عربية."""

    impl = String
    cache_ok = True

    def process_result_value(self, value, dialect):  # noqa: D102 — SQLAlchemy hook
        return arabic.eastern_digits(value)
