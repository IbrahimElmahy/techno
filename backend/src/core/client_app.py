"""الطلب جاي من تطبيق الموبايل ولا من الويب؟

التطبيق بيسحب قوايمه (العملاء، الملّاك، القوايم) من نفس المسارات اللي شاشات الإدارة في
الويب بتقرا منها — والشاشات دي لازم تشوف الموقوف عشان ترجّعه. التطبيق مابيبعتش
`active` ولا `active_only`، فالموقوف كان بيوصل الجهاز ويتعرض للمندوب (٢٠٢٦-١٠-٠٧).

الفلترة هنا عشان الإصلاح يوصل **من غير نسخة تطبيق جديدة**: الأجهزة اللي في الشارع
بتبعت نفس الطلب، والسيرفر هو اللي بيشيل الموقوف. نسخة التطبيق الجاية المفروض تبعت
الفلتر صراحةً، والشرط ده يفضل للنسخ القديمة.

التطبيق Flutter بـ`package:http` على `dart:io`، وده بيبعت `User-Agent: Dart/<ver> (dart:io)`
لوحده (متأكدين من لوج nginx على الإنتاج). مافيش متصفح بيبعت كده، فالويب مابيتأثرش.
"""
from __future__ import annotations

from fastapi import Request


def is_mobile_app(request: Request) -> bool:
    return request.headers.get("user-agent", "").startswith("Dart/")
